function taxDefaultPackCode() {
  const cc = typeof regionCountry === "function" ? regionCountry() : "";
  if (cc === "MY") return "MYS";
  if (cc === "SG") return "SGP";
  if (cc === "HK") return "HKG";
  return "GLOBAL";
}

function taxPackRaw(code) {
  const c = String(code || "").toUpperCase();
  if (c === "MYS") {
    if (typeof TAX_DATA === "undefined" || !TAX_DATA) return null;
    return {
      ...TAX_DATA,
      country_code: "MYS",
      currency: "MYR",
      mode: "pack",
      overall_relief_cap: null,
      withholding_mode: "paye",
      zakat_mode: "rebate",
      fiscal_year: {
        start_mm_dd: "01-01",
        end_mm_dd: "12-31",
        assessment_basis: "current",
        label_format: "single",
      },
    };
  }
  if (c === "SGP") return TAX_PACK_SGP;
  if (c === "HKG") return TAX_PACK_HKG;
  if (c === "GLOBAL") return TAX_PACK_GLOBAL;
  return null;
}
